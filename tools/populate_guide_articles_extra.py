def main() -> int:
    text = OUT.read_text(encoding="utf-8-sig")
    reader = csv.DictReader(text.splitlines())
    fieldnames = list(reader.fieldnames or [])
    rows = list(reader)
    existing = {r["slug"] for r in rows if r.get("slug")}

    for art in NEW_ARTICLES:
        if art["slug"] in existing:
            continue
        row = {k: "" for k in fieldnames}
        row.update(COMMON)
        row.update(art)
        for n in range(1, 8):
            row.setdefault(f"section_{n}_heading", "")
            row.setdefault(f"section_{n}_body", "")
        rows.append(row)

    rows.sort(key=lambda r: -int(r.get("priority") or 0))
    with OUT.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)

    added = sum(1 for a in NEW_ARTICLES if a["slug"] not in existing)
    print(f"guide_articles.csv: added {added} articles ({len(rows)} total)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

def mk(
    slug: str,
    genre: str,
    title: str,
    meta_description: str,
    lead: str,
    priority: str,
    tags: str,
    user_intent: str,
    action_items: str,
    sections: list[tuple[str, str]],
    faqs: list[tuple[str, str]],
    related_links: str,
    original_note: str = "",
) -> dict[str, str]:
    row: dict[str, str] = {
        "slug": slug,
        "genre": genre,
        "title": title,
        "meta_description": meta_description,
        "lead": lead,
        "priority": priority,
        "tags": tags,
        "user_intent": user_intent,
        "action_items": action_items,
        "related_links": related_links,
        "original_note": original_note or title,
    }
    for i, (h, b) in enumerate(sections, start=1):
        row[f"section_{i}_heading"] = h
        row[f"section_{i}_body"] = b
    for i in range(len(sections) + 1, 8):
        row[f"section_{i}_heading"] = ""
        row[f"section_{i}_body"] = ""
    for i, (q, a) in enumerate(faqs, start=1):
        row[f"faq_{i}_question"] = q
        row[f"faq_{i}_answer"] = a
    for i in range(len(faqs) + 1, 4):
        row[f"faq_{i}_question"] = ""
        row[f"faq_{i}_answer"] = ""
    return row



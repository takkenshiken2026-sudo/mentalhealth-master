def main() -> int:
    if len(NEW_TERMS) < 50:
        print(f"expected at least 50 terms, got {len(NEW_TERMS)}", file=sys.stderr)
        return 1
    batch = NEW_TERMS[:50]

    with CSV_PATH.open(encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        fieldnames = list(reader.fieldnames or [])
        existing_rows = list(reader)

    existing_terms = {r.get("term", "").strip() for r in existing_rows}
    to_add: list[dict[str, str]] = []
    for term, category, short_def, body, related, legal, importance in batch:
        if term in existing_terms:
            print(f"skip (exists): {term}", file=sys.stderr)
            continue
        to_add.append(
            {
                "term": term,
                "reading": term,
                "category": category,
                "tags": category,
                "short_def": short_def,
                "definition": body,
                "related_terms": related,
                "legal_basis": legal,
                "importance": importance,
                "explanation": body,
            }
        )

    if not to_add:
        print("no new terms to add", file=sys.stderr)
        return 1

    merged = existing_rows + to_add
    with CSV_PATH.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        w.writeheader()
        w.writerows(merged)

    print(f"Added {len(to_add)} terms → {CSV_PATH} (total {len(merged)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

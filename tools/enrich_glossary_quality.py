def norm(s: str | None) -> str:
    return (s or "").strip()


def split_definition_exam(definition: str) -> tuple[str, str]:
    """定義本文と試験用（誤選択肢）文を分離。"""
    text = norm(definition)
    if not text:
        return "", ""
    m = re.search(r"(試験では.+?)(?:。|$)", text)
    if m:
        exam = m.group(1).rstrip("。") + "。"
        base = text[: m.start()].strip()
        if base and not base.endswith("。"):
            base += "。"
        return base, exam
    return text, "選択肢では根拠法令・対象範囲・責任の所在がずれる肢に注意し、用語の定義と照合してください。"


def extract_legacy_parts(term: str, short_def: str, definition: str) -> tuple[str, str]:
    """既存289語のテンプレート定義から、定義本文と試験向け文を抽出。"""
    text = norm(definition)
    sd = norm(short_def)
    m_key = re.search(r"まず「([^」]+)」", text)
    m_past = re.search(r"過去問・演習では「([^」]+)」", text)

    body_parts: list[str] = []
    if sd:
        body_parts.append(sd.rstrip("。") + "。")
    if m_key:
        body_parts.append(m_key.group(1).rstrip("。") + "。")
    body = "".join(body_parts) if body_parts else text

    if m_past:
        exam = (
            f"演習の正答の要点は「{m_past.group(1)}」です。"
            "誤り肢は根拠法令の取り違え、対象範囲の限定（のみ・必ず）、"
            "責任主体の混同（会社のみ・管理監督者のみ）に注意してください。"
        )
    elif m_key:
        exam = (
            f"選択肢では「{m_key.group(1)}」と矛盾する記述が誤りになりやすいです。"
            "数値・手順・誰が担うかをセットで確認してください。"
        )
    else:
        _, exam = split_definition_exam(text)
    return body, exam


def apply_practice_link(row: dict[str, str], mapping: dict[str, tuple[str, str]]) -> None:
    term = norm(row.get("term"))
    if norm(row.get("practice_question")):
        return
    pq = mapping.get(term)
    if pq:
        row["practice_question"] = pq[0]
        row["practice_question_label"] = pq[1]


def practice_path(question_no: int) -> str:
    return f"y2026/q{question_no:02d}" if question_no < 100 else f"y2026/q{question_no}"


def practice_search_keys(term: str) -> list[str]:
    keys: list[str] = [term]
    if "（" in term:
        keys.append(term.split("（")[0])
        inner = term.split("（", 1)[1].rstrip("）")
        if inner:
            keys.append(inner)
    if len(term) >= 4:
        keys.append(term[:6])
    return keys


def fallback_practice_q(term: str, category: str) -> tuple[str, str] | None:
    for keys, pq in KEYWORD_FALLBACK_Q:
        if any(k in term for k in keys):
            return pq
    return CATEGORY_FALLBACK_Q.get(category)


def build_auto_practice_q(terms: list[str]) -> dict[str, tuple[str, str]]:
    """past_questions.csv から用語名で演習問題を検索。"""
    if not PAST_QUESTIONS_CSV.is_file():
        return {}
    rows = list(csv.DictReader(PAST_QUESTIONS_CSV.read_text(encoding="utf-8-sig").splitlines()))
    out: dict[str, tuple[str, str]] = {}
    for term in terms:
        n: int | None = None
        for r in rows:
            if r.get("exam_year") != "2026" or r.get("exam_wareki") != "演習":
                continue
            blob = " ".join(str(r.get(k, "")) for k in r)
            for key in practice_search_keys(term):
                if len(key) >= 3 and key in blob:
                    n = int(r["question_no"])
                    break
            if n:
                break
        if n:
            short = term if len(term) <= 24 else term[:22] + "…"
            out[term] = (practice_path(n), f"演習2026・第{n}問（{short}）")
    return out


def build_auto_practice_q_full(rows: list[dict[str, str]], enriched: frozenset[str]) -> dict[str, tuple[str, str]]:
    """残り用語: CSV検索 → キーワード/カテゴリフォールバック。"""
    terms = [norm(r.get("term")) for r in rows if norm(r.get("term")) and norm(r.get("term")) not in enriched]
    out = build_auto_practice_q(terms)
    for r in rows:
        term = norm(r.get("term"))
        if not term or term in enriched or term in out:
            continue
        fb = fallback_practice_q(term, norm(r.get("category")))
        if fb:
            out[term] = fb
    return out



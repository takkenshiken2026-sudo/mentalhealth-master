def update_guide_glossary_count(term_count: int) -> bool:
    if not GUIDE_CSV.is_file():
        return False
    text = GUIDE_CSV.read_text(encoding="utf-8-sig")
    reader = csv.DictReader(text.splitlines())
    fieldnames = list(reader.fieldnames or [])
    rows = list(reader)
    changed = False
    for row in rows:
        if norm(row.get("slug")) != "glossary-how-to":
            continue
        for key in fieldnames:
            val = row.get(key) or ""
            if "289語" in val:
                row[key] = val.replace("289語", f"{term_count}語")
                changed = True
    if changed:
        with GUIDE_CSV.open("w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
            w.writeheader()
            w.writerows(rows)
    return changed


def main() -> int:
    with CSV_PATH.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        fieldnames = list(reader.fieldnames or [])
        rows = list(reader)
    for col in ("practice_question", "practice_question_label"):
        if col not in fieldnames:
            fieldnames.append(col)

    top20 = patch_top20()
    enriched = enriched_terms(set(top20.keys()))
    pq_auto = build_auto_practice_q_full(rows, enriched)
    n_top = n_light = n_batch_done = n_legacy = n_flat = 0

    for row in rows:
        term = norm(row.get("term"))
        if term in top20:
            for k, v in top20[term].items():
                row[k] = v
            apply_practice_link(row, PRACTICE_Q)
            n_top += 1
        elif light_patch_batch50(row):
            n_light += 1
        if term in BATCH50_TERMS and finalize_batch50(row):
            n_batch_done += 1
        if patch_legacy_next30(row):
            n_legacy += 1
        if patch_remaining_flat(row, pq_auto, enriched):
            n_flat += 1

    term_count = len([r for r in rows if norm(r.get("term"))])
    batch_pq = sum(
        1 for r in rows if norm(r.get("term")) in BATCH50_TERMS and norm(r.get("practice_question"))
    )
    legacy_pq = sum(
        1 for r in rows if norm(r.get("term")) in LEGACY_PATCH_TERMS and norm(r.get("practice_question"))
    )
    pq_total = sum(1 for r in rows if norm(r.get("practice_question")))
    guide_ok = update_guide_glossary_count(term_count)

    with CSV_PATH.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)

    print(
        f"quality: top20={n_top}, batch50_light={n_light}, batch50_pq={batch_pq}/50, "
        f"legacy={n_legacy}/{len(LEGACY_PATCH_TERMS)}, legacy_pq={legacy_pq}, "
        f"flat={n_flat}/{len(pq_auto)}, pq_total={pq_total}/{term_count}, "
        f"terms={term_count}, guide_updated={guide_ok}"
    )

    from tools.rewrite_glossary_handcrafted import main as handcrafted_main
    from tools.enrich_glossary_readability import main as readability_main
    from tools.enrich_glossary_pro_writer import main as glossary_pro_main
    from tools.enrich_guide_pro_writer import main as guide_pro_main

    handcrafted_main()
    readability_main()
    glossary_pro_main()
    guide_pro_main()
    return 0


